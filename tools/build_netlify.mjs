#!/usr/bin/env node
// Public DEMO only. Never copy the repository root or local private/ content.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
const marker = '<!-- Generated by tools/build_netlify.mjs; public DEMO only. -->';
const rootFiles = ['index.html', 'app.js', 'content.js', 'styles.css', 'light-theme.css', 'peony-theme.css', 'exhibits.css'];

function fail(message) { throw new Error(message); }
function filesIn(directory, prefix = '') {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) fail(`Symlinks are not allowed: ${relative}`);
    if (entry.isDirectory()) files.push(...filesIn(path.join(directory, entry.name), relative));
    else if (entry.isFile()) files.push(relative);
    else fail(`Unsupported file type: ${relative}`);
  }
  return files.sort();
}

// Restrict this public demo to the existing SVG illustrations, never photo originals.
if (!fs.lstatSync(path.join(root, 'assets')).isDirectory()) fail('assets must be a regular directory.');
const assets = filesIn(path.join(root, 'assets'), 'assets');
for (const asset of assets) {
  if (!/^assets\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_-]+\.svg$/.test(asset)) {
    fail(`Only public SVG demo assets may be deployed: ${asset}`);
  }
}
const allowed = new Set([...rootFiles, ...assets]);
for (const relative of allowed) {
  if (!fs.lstatSync(path.join(root, relative)).isFile()) fail(`Expected a regular file: ${relative}`);
}

const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'content.js'), 'utf8'), context, { timeout: 1000 });
const content = context.window.MUSEUM_CONTENT;
if (!content || content.demoMode !== true) fail('Public content.js must have demoMode: true.');
if (content.since !== null) fail('Public demo must not contain a real relationship start date.');
function checkContent(value) {
  if (typeof value === 'string') {
    if (/\bprivate[\\/]/i.test(value)) fail('Public content contains a private/ reference.');
    if (value.startsWith('assets/') && !allowed.has(value)) fail(`Missing public asset: ${value}`);
  } else if (value && typeof value === 'object') {
    for (const item of Object.values(value)) checkContent(item);
  }
}
checkContent(content);

function outputContents(relative) {
  const source = fs.readFileSync(path.join(root, relative));
  if (relative !== 'index.html') return source;
  const html = source.toString('utf8');
  const htmlTag = html.match(/<html\b[^>]*>/gi);
  if (htmlTag?.length !== 1 || /\bdata-content-mode\s*=/i.test(htmlTag[0])) {
    fail('Expected one source html tag without a deployment content mode.');
  }
  return Buffer.from(html.replace(/<html\b/i, '<html data-content-mode="demo"') + `\n${marker}\n`);
}
// Validate the deploy-only flag before replacing any previous output.
outputContents('index.html');

// Check static HTML/CSS/JS asset references before touching an earlier build.
for (const relative of rootFiles) {
  const source = fs.readFileSync(path.join(root, relative), 'utf8');
  for (const match of source.matchAll(/(?:src|href)=["']([^"']+)["']/g)) {
    const reference = match[1].split(/[?#]/)[0];
    if (/^(?:https?:|data:|#|\$\{)/.test(reference) || reference === '') continue;
    if (!allowed.has(reference)) fail(`Unpublished reference in ${relative}: ${reference}`);
  }
  for (const match of source.matchAll(/(?:["'(])((?:assets\/)[A-Za-z0-9_./-]+)/g)) {
    if (!allowed.has(match[1])) fail(`Missing asset in ${relative}: ${match[1]}`);
  }
}

if (fs.existsSync(output)) {
  if (!fs.lstatSync(output).isDirectory()) fail('Existing dist is not a regular directory.');
  const previousIndex = path.join(output, 'index.html');
  if (!fs.existsSync(previousIndex) || !fs.readFileSync(previousIndex, 'utf8').trimEnd().endsWith(marker)) {
    fail('Refusing to replace an unrecognized dist directory. Move it aside first.');
  }
  for (const relative of filesIn(output)) {
    if (!allowed.has(relative)) fail(`Refusing to remove an unknown dist file: ${relative}`);
  }
  fs.rmSync(output, { recursive: true });
}

fs.mkdirSync(output);
for (const relative of allowed) {
  const destination = path.join(output, relative);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, outputContents(relative));
}

// Direct content comparison: all output files must come from the explicit allowlist.
const built = filesIn(output);
if (built.length !== allowed.size) fail('Unexpected output file count.');
for (const relative of built) {
  if (!allowed.has(relative)) fail(`Unexpected output file: ${relative}`);
  const expected = outputContents(relative);
  if (!fs.readFileSync(path.join(output, relative)).equals(expected)) fail(`Copy mismatch: ${relative}`);
}
console.log(`Public DEMO build verified: ${built.length} files (${assets.length} SVG assets).`);
console.log(`Publish directory: ${output}`);
